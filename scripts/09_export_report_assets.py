#!/usr/bin/env python
"""Step 9 - turn results/ into the files the LaTeX report \\input's.

* report/generated/macros.tex   every scalar in results/numbers/*.json
* report/generated/tab_*.tex    table bodies
* report/figures/*.pdf          vector copies of the figures

Because the report reads its numbers from here, re-running the pipeline on
new data and recompiling keeps text, tables and figures consistent.
"""
from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from nsenet.config import REPO_ROOT, load_config  # noqa: E402

GEN = REPO_ROOT / "report" / "generated"
FIG = REPO_ROOT / "report" / "figures"


def esc(text) -> str:
    return str(text).replace("&", r"\&").replace("%", r"\%").replace("_", r"\_").replace("#", r"\#")


def fmt(x, digits=3, pct=False, integer=False) -> str:
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return "--"
    if integer:
        return f"{int(round(x)):,}".replace(",", "{,}")
    if pct:
        return f"{100 * x:.{digits}f}"
    return f"{x:.{digits}f}"


def pval(p) -> str:
    if not np.isfinite(p):
        return "--"
    return r"$<$0.001" if p < 0.001 else f"{p:.3f}"


def write(name: str, lines: list[str]) -> None:
    (GEN / f"{name}.tex").write_text("\n".join(lines) + "\n")


def macros() -> None:
    out = ["% AUTO-GENERATED by scripts/09_export_report_assets.py - do not edit by hand."]
    for path in sorted((REPO_ROOT / "results" / "numbers").glob("*.json")):
        for key, value in json.loads(path.read_text()).items():
            name = f"{path.stem}.{key}"
            if isinstance(value, bool):
                value = "yes" if value else "no"
            elif isinstance(value, float):
                value = "nan" if not np.isfinite(value) else repr(float(value))
            elif isinstance(value, str):
                value = esc(value)
            out.append(rf"\expandafter\def\csname v@{name}\endcsname{{{value}}}")
    write("macros", out)


def tables(cfg: dict) -> None:
    t = Path(cfg["output"]["tables_dir"])
    r_star, r_back = cfg["network"]["baseline_threshold"], cfg["network"]["backbone_threshold"]

    # --- extreme-return audit: all masked + the ten largest genuine ---------
    a = pd.read_csv(t / "data_extreme_return_audit.csv").fillna("")
    masked = a[a["classification"].str.startswith("mechanical")]
    genuine = a[~a["classification"].str.startswith("mechanical")].head(10)
    rows = []
    for _, r in pd.concat([masked, genuine]).iterrows():
        is_masked = r["classification"].startswith("mechanical")
        note = r["note"] if r["note"] else "company-specific news"
        rows.append(f"{r['date']} & {esc(r['ticker'][:-3])} & ${r['simple_return_pct']:+.1f}$ & "
                    f"{fmt(r['volume_multiple'], 1)} & {'masked' if is_masked else 'kept'} & {esc(note)} \\\\")
        if _ == masked.index[-1]:
            rows.append(r"\midrule")
    write("tab_audit", rows)

    # --- sector composition -------------------------------------------------
    s = pd.read_csv(t / "data_sector_composition.csv")
    c = pd.read_csv(t / f"C_sector_cohesion_r{r_star:.2f}.csv").set_index("sector")
    rows = [f"{esc(r.sector)} & {r.in_index} & {r.in_network} & {r.psu_in_network} \\\\" for r in s.itertuples()]
    rows += [r"\midrule", f"Total & {s.in_index.sum()} & {s.in_network.sum()} & {s.psu_in_network.sum()} \\\\"]
    write("tab_sectors", rows)

    # --- tail model comparison ---------------------------------------------
    rows = []
    for r in (r_star, r_back):
        m = pd.read_csv(t / f"A_tail_model_comparison_r{r:.2f}.csv")
        full = pd.read_csv(t / f"A_full_model_comparison_r{r:.2f}.csv").set_index("model")
        for i, x in enumerate(m.itertuples()):
            lead = rf"\multirow{{4}}{{*}}{{${r:.2f}$}}" if i == 0 else ""
            llr = "--" if x.model == "power law" else f"{x.llr_powerlaw_vs_model:+.1f}"
            pv = "--" if x.model == "power law" else pval(x.vuong_p)
            rows.append(f"{lead} & {x.model} & {fmt(x.loglik, 1)} & {fmt(x.delta_aic, 1)} & {llr} & {pv} & "
                        f"{fmt(full.loc[x.model, 'delta_aic'], 1)} \\\\")
        if r == r_star:
            rows.append(r"\midrule")
    write("tab_tailfits", rows)

    # --- power-law ladder ---------------------------------------------------
    lad = pd.read_csv(t / "A_powerlaw_test_by_threshold.csv")
    rows = []
    for x in lad.itertuples():
        alpha = r"$\geq 12$" if x.alpha > 11.9 else fmt(x.alpha, 2)
        rows.append(f"{x.threshold:.2f} & {int(x._2)} & {fmt(x.mean_degree, 1)} & {x.max_degree} & {x.kmin} & {x.n_tail} & "
                    f"{alpha} & {fmt(x.gof_p, 2)} & {x.llr_vs_exp:+.1f} & {pval(x.vuong_p_vs_exp)} & {x.best_model_aic} \\\\")
    write("tab_ladder", rows)

    # --- leaderboards -------------------------------------------------------
    for r, tag in ((r_star, "star"), (r_back, "back")):
        lb = pd.read_csv(t / f"B_top10_leaderboard_r{r:.2f}.csv")
        rows = []
        for x in lb.itertuples():
            cells = [str(x.rank)]
            for m in ("degree", "betweenness", "eigenvector"):
                star = r"$^{\ast}$" if getattr(x, f"{m}_psu") else ""
                cells += [esc(getattr(x, f"{m}_stock")) + star, esc(getattr(x, f"{m}_sector")), fmt(getattr(x, f"{m}_value"), 3)]
            rows.append(" & ".join(cells) + r" \\")
        write(f"tab_leaderboard_{tag}", rows)

    # --- heavyweights -------------------------------------------------------
    hw = pd.read_csv(t / "B_heavyweights.csv", index_col=0)
    rows = [f"{esc(i)} & {esc(x.sector)} & {int(x.size_rank)} & {fmt(x.rho_market, 2)} & {int(x.degree)} & "
            f"{int(x.rank_degree_centrality)} & {int(x.rank_betweenness)} & {int(x.rank_eigenvector)} & {int(x.degree_backbone)} \\\\"
            for i, x in hw.iterrows()]
    write("tab_heavy", rows)

    # --- sector cohesion ----------------------------------------------------
    rows = []
    cb = pd.read_csv(t / f"C_sector_cohesion_r{r_back:.2f}.csv").set_index("sector")
    for sec, x in c[c["n_stocks"] >= 9].iterrows():
        ratio = fmt(x.density_ratio, 1) if np.isfinite(x.density_ratio) else "--"
        rows.append(f"{esc(sec)} & {int(x.n_stocks)} & {int(x.n_isolated)} & {fmt(x.mean_degree, 1)} & {int(x.internal_edges)} & "
                    f"{fmt(x.internal_density, 3)} & {fmt(x.external_density, 3)} & {ratio} & "
                    f"{fmt(x.mean_clustering_deg2plus, 2)} & {fmt(cb.loc[sec, 'internal_density'], 3)} \\\\")
    write("tab_sector_cohesion", rows)

    # --- threshold sweep ----------------------------------------------------
    sw = pd.read_csv(t / "D_threshold_sweep_coarse.csv")
    rows = []
    for x in sw.itertuples():
        rows.append(f"{x.threshold:.2f} & {fmt(x.n_edges, integer=True)} & {fmt(x.density, 2, pct=True)} & {fmt(x.mean_degree, 1)} & "
                    f"{x.n_isolated} & {x.gcc_size} & {fmt(x.gcc_fraction, 1, pct=True)} & {fmt(x.avg_path_length, 2)} & "
                    f"{int(x.diameter)} & {fmt(x.avg_clustering, 3)} & {fmt(x.transitivity, 3)} & "
                    f"{fmt(x.intra_sector_fraction, 1, pct=True)} \\\\")
    write("tab_sweep", rows)

    # --- raw vs residual ----------------------------------------------------
    rr = pd.read_csv(t / "E1_raw_vs_residual_network.csv")
    labels = [("edges", "Edges $M$", lambda v: fmt(v, integer=True)), ("threshold", "Threshold applied", lambda v: fmt(v, 3)),
              ("isolated", "Isolated stocks", lambda v: fmt(v, integer=True)), ("gcc", "Giant component", lambda v: fmt(v, integer=True)),
              ("max_degree", "Maximum degree", lambda v: fmt(v, integer=True)), ("degree_gini", "Gini coefficient of degree", lambda v: fmt(v, 2)),
              ("transitivity", "Transitivity", lambda v: fmt(v, 3)),
              ("intra_sector_fraction", r"Same-sector share of edges (\%)", lambda v: fmt(v, 1, pct=True)),
              ("sector_assortativity", "Sector assortativity", lambda v: fmt(v, 3)),
              ("psu_assortativity", "Ownership (PSU) assortativity", lambda v: fmt(v, 3)),
              ("mono_sector_triangles", r"Single-sector triangles (\%)", lambda v: fmt(v, 1, pct=True))]
    rows = [f"{lab} & " + " & ".join(f(v) for v in rr[key]) + r" \\" for key, lab, f in labels]
    write("tab_residual", rows)

    # --- bootstrap leaderboard ---------------------------------------------
    rows = []
    b1 = pd.read_csv(t / f"E2_bootstrap_top10_frequency_r{r_star:.2f}.csv", index_col=0).head(12)
    b2 = pd.read_csv(t / f"E2_bootstrap_top10_frequency_r{r_back:.2f}.csv", index_col=0).head(12)
    for (i1, x1), (i2, x2) in zip(b1.iterrows(), b2.iterrows()):
        s1 = r"$^{\ast}$" if x1.psu else ""
        s2 = r"$^{\ast}$" if x2.psu else ""
        rows.append(f"{esc(i1)}{s1} & {int(x1.degree_full_sample)} & {fmt(x1.boot_mean_degree, 0)} $\\pm$ {fmt(x1.boot_sd_degree, 0)} & "
                    f"{fmt(x1.freq_in_top10, 0, pct=True)} & {esc(i2)}{s2} & {int(x2.degree_full_sample)} & "
                    f"{fmt(x2.boot_mean_degree, 0)} $\\pm$ {fmt(x2.boot_sd_degree, 0)} & {fmt(x2.freq_in_top10, 0, pct=True)} \\\\")
    write("tab_bootstrap", rows)

    # --- turbulent days -----------------------------------------------------
    inf = pd.read_csv(t / "E2_turbulent_day_influence.csv")
    rows = []
    for x in inf.itertuples():
        rows.append(f"{x.days_removed} & {fmt(x.mean_correlation, 3)} & {fmt(x.edges_star, integer=True)} & {x.gcc_star} & "
                    f"{fmt(x.sector_assort_star, 2)} & {fmt(x.psu_assort_star, 2)} & {x.top10_overlap_star} & "
                    f"{fmt(x.edges_back, integer=True)} & {x.gcc_back} & {fmt(x.sector_assort_back, 2)} & "
                    f"{fmt(x.psu_assort_back, 2)} & {x.top10_overlap_back} \\\\")
    write("tab_turbulent", rows)

    # --- top correlated pairs ----------------------------------------------
    pairs = pd.read_csv(t / "data_top_correlated_pairs.csv").head(12)
    rows = [f"{esc(x.stock_a)} -- {esc(x.stock_b)} & {esc(x.sector_a)}{'' if x.sector_a == x.sector_b else ' / ' + esc(x.sector_b)} & "
            f"{fmt(x.rho, 3)} \\\\" for x in pairs.itertuples()]
    write("tab_pairs", rows)

    # --- cliques ------------------------------------------------------------
    cl = pd.read_csv(t / "C_largest_cliques_backbone.csv").head(1)
    write("tab_clique", [esc(cl["members"].iloc[0]).replace(" ", ", ")])


def main() -> None:
    cfg = load_config()
    GEN.mkdir(parents=True, exist_ok=True)
    FIG.mkdir(parents=True, exist_ok=True)
    macros()
    tables(cfg)
    for pdf in Path(cfg["output"]["figures_dir"]).glob("*.pdf"):
        shutil.copy2(pdf, FIG / pdf.name)
    print(f"wrote {len(list(GEN.glob('*.tex')))} generated files to {GEN}")
    print(f"copied {len(list(FIG.glob('*.pdf')))} figures to {FIG}")


if __name__ == "__main__":
    main()
